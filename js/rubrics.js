export const DEFAULT_RUBRIC = 'p56';

export function rubricForGrade(grade) {
  return Object.keys(RUBRICS).find((k) => RUBRICS[k].grades.includes(grade)) || DEFAULT_RUBRIC;
}

export function cloneItems(key) {
  return RUBRICS[key].items.map((i) => ({ ...i }));
}
