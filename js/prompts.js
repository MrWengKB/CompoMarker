export const CONTINUE_MARK = '〔续〕';

// 多页时逐页识别，避免一次上传过大
export function ocrPageText(index, total) {
  if (total <= 1) return '请转写这篇作文。';
  if (index === 0) return `这篇作文共 ${total} 页，这是第 1 页，请转写这一页。`;
  return `这篇作文共 ${total} 页，这是第 ${index + 1} 页，请只转写这一页。这一页不要输出「学生：」和「标题：」。如果这一页开头是在接着上一页没写完的段落（第一行开头没有空两格），请在输出的最前面加上「${CONTINUE_MARK}」；如果开头就是新的一段，则不要加。`;
}

